import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const base='http://localhost:5173'
const catalogue=await (await fetch(`${base}/api/rest-areas`)).json()
const target=catalogue.rows.find(row=>row.name.includes('죽전'))
assert.ok(target)
const response=await fetch(`${base}/api/menus?id=${encodeURIComponent(target.id)}`)
const menus=await response.json()
assert.equal(response.status,200)
assert.ok(menus.rows.length>0)
assert.equal(menus.area.id,target.id)
assert.ok(menus.rows.every(row=>row.code===target.code))
assert.equal((await fetch(`${base}/api/menus?id=not-real`)).status,404)
const browser=await chromium.launch({channel:'msedge',headless:true})
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}}), errors=[]
 page.on('pageerror',error=>errors.push(error.message))
 await page.route('**/api/menus',route=>route.fulfill({json:{rows:[],count:0}}))
 await page.goto(`${base}/#menus`)
 const road=page.getByRole('combobox',{name:'음식 메뉴 노선',exact:true})
 const direction=page.getByRole('combobox',{name:'음식 메뉴 방향',exact:true})
 const rest=page.getByRole('combobox',{name:'음식 메뉴 휴게소',exact:true})
 await road.waitFor()
 assert.equal(await road.locator('img').count(),0)
 assert.equal(await direction.locator('img').count(),0)
 assert.ok(await direction.isDisabled());assert.ok(await rest.isDisabled())
 await road.click();await page.getByRole('option',{name:/경부선/}).click()
 assert.equal(await road.locator('.road-badge').innerText(),'1')
 await direction.click()
 const label=(target.directions?.[0] || '서울').replace(/방향$/,'').trim()
 await page.getByRole('option',{name:new RegExp(label)}).click()
 assert.equal(await direction.locator('.direction-highway-icon').count(),1)
 assert.equal(await direction.locator('.road-badge').count(),0)
 await rest.click();await page.getByRole('option',{name:target.name,exact:true}).click()
 await page.getByRole('button',{name:'메뉴 검색',exact:true}).click()
 await page.locator('.content-panel>.responsive-table tbody tr').first().waitFor({timeout:45000})
 assert.equal(await page.locator('.content-panel>.responsive-table tbody tr').count(),Math.min(menus.rows.length,15))
 assert.ok((await page.locator('.content-panel>.responsive-table tbody tr td[data-label="휴게소"]').allTextContents()).every(name=>name.includes('죽전')))
 await page.screenshot({path:'artifacts/menu-route-desktop.png',fullPage:true})
 await road.click();await page.getByRole('option',{name:/영동선/}).click()
 assert.ok((await direction.innerText()).endsWith('방향 선택'));assert.ok(await rest.isDisabled())
 for(const width of [768,390,320]){
  await page.setViewportSize({width,height:950})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),`Menu overflow ${width}`)
 }
 await page.screenshot({path:'artifacts/menu-route-mobile.png',fullPage:true})
 await page.goto(`${base}/#shelters`)
 await page.locator('.shelter-card').first().waitFor({timeout:45000})
 const shelterRoad=page.getByRole('combobox',{name:'졸음쉼터 노선',exact:true})
 await shelterRoad.click();await page.getByRole('option',{name:/대구외곽순환선/}).click()
 assert.equal(await shelterRoad.locator('.road-badge.long-number').innerText(),'700')
 assert.ok(await page.locator('.shelter-card-top .road-badge.long-number').count()>0)
 assert.ok(await page.locator('.shelter-card-top .direction-highway-icon').count()>0)
 await page.screenshot({path:'artifacts/shelters-numbered-mobile.png',fullPage:true})
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth))
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({passed:true,selectedStop:target.name,menus:menus.rows.length,checks:['live filtered API','invalid ID 404','cascade resets','numbered shields','320/390/768 responsive','no browser errors']}))
}finally{await browser.close()}

