import fs from 'node:fs'
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { settings } from '../server/api.js'

const browser=await chromium.launch({channel:'msedge',headless:true})
const context=await browser.newContext({viewport:{width:1440,height:1050}})
const page=await context.newPage(),errors=[]
const keys=Object.entries(settings()).filter(([name])=>name.endsWith('_KEY')).map(([,value])=>value).filter(Boolean)
const sanitize=message=>keys.reduce((result,key)=>result.replaceAll(key,'[REDACTED]'),message)
page.on('pageerror',error=>errors.push(sanitize(error.message)))
fs.mkdirSync('artifacts',{recursive:true})
const root=process.env.CHECK_URL||'http://localhost:5173'
try {
  await page.goto(root,{waitUntil:'domcontentloaded'})
  await page.getByRole('heading',{name:/전체 휴게소/}).waitFor()
  await page.locator('.area-card').first().waitFor({timeout:45000})
  await page.waitForFunction(()=>/\d/.test(document.querySelectorAll('.summary-grid article strong')[1]?.textContent||''),{},{timeout:60000})
  await page.waitForSelector('.map-toolbar .success',{timeout:30000})
  await page.waitForTimeout(1600)
  await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo(0,0)})
  await page.screenshot({path:'artifacts/desktop.png',fullPage:true})
  await page.locator('.area-open').first().click()
  await page.getByRole('dialog').waitFor()
  await page.getByRole('tab',{name:'음식 메뉴'}).click()
  await page.locator('.detail-items article').first().waitFor({timeout:45000})
  assert.ok(await page.locator('.detail-items article').count()>0)
  await page.keyboard.press('Escape')
  await page.locator('.compare-check input').nth(0).check()
  await page.locator('.compare-check input').nth(1).check()
  await page.getByRole('button',{name:'선택한 휴게소 비교'}).click()
  await page.locator('.comparison-table').waitFor({timeout:45000})
  assert.equal(await page.locator('.comparison-table thead th').count(),3)
  await page.keyboard.press('Escape')
  await page.locator('.compare-check input').nth(0).uncheck()
  await page.locator('.compare-check input').nth(1).uncheck()
  await page.evaluate(()=>document.activeElement?.blur())
  for(const viewport of [{width:768,height:1024},{width:390,height:844},{width:320,height:750}]) {
    await page.setViewportSize(viewport)
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),`overflow at ${viewport.width}`)
    if(viewport.width===390)await page.screenshot({path:'artifacts/mobile.png',fullPage:true})
  }
  await page.setViewportSize({width:1440,height:1050})
  await page.getByRole('textbox',{name:'출발지',exact:true}).fill('서울역')
  await page.getByRole('button',{name:'출발지 장소 검색'}).click()
  await page.locator('.place-results button').first().waitFor({timeout:30000})
  await page.locator('.place-results button').first().click()
  await page.getByRole('textbox',{name:'도착지',exact:true}).fill('부산역')
  await page.getByRole('button',{name:'도착지 장소 검색'}).click()
  await page.locator('.place-results button').first().waitFor({timeout:30000})
  await page.locator('.place-results button').first().click()
  await page.getByRole('button',{name:'경로 검색',exact:true}).click()
  await page.locator('.route-result').waitFor({timeout:45000})
  await page.waitForTimeout(1200)
  await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo(0,0)})
  await page.screenshot({path:'artifacts/route.png',fullPage:true})
  await page.goto(root+'/#menus')
  await page.locator('.responsive-table tbody tr').first().waitFor({timeout:45000})
  await page.getByRole('textbox',{name:'음식 메뉴 검색'}).fill('농심어묵우동')
  assert.ok((await page.locator('.responsive-table tbody').innerText()).includes('농심어묵우동'))
  await page.screenshot({path:'artifacts/menus.png',fullPage:true})
  await page.goto(root+'/#statistics')
  await page.locator('.statistics-chart .recharts-wrapper').waitFor({timeout:45000})
  await page.getByRole('button',{name:'2024 차량 통행량'}).click()
  assert.ok((await page.locator('.chart-heading').innerText()).includes('2024'))
  await page.screenshot({path:'artifacts/statistics.png',fullPage:true})
  for(const view of ['menus','facilities','statistics','sources','directory']) {
    await page.goto(root+'/#'+view)
    await page.locator('.content-panel').waitFor()
    await page.setViewportSize({width:390,height:844})
    await page.waitForTimeout(500)
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),`${view}: mobile overflow`)
  }
  assert.equal(errors.length,0,errors.join('\n'))
  console.log(JSON.stringify({passed:true,checked:['actual data','Kakao map','detail menus','2-area comparison','320/390/768 responsiveness','actual Seoul-Busan route','menu search','separate-year charts'],screenshots:'artifacts/'}))
} finally { await browser.close() }
